import {
    ResponsiveContainer,
    LineChart,
    Line,
    CartesianGrid,
    XAxis,
    YAxis,
    Tooltip
} from "recharts";

export default function PlantationChart({

    dashboard = [],

    summary = {}

}) {

    const chartData = dashboard

        .slice(0, 10)

        .map((ward, index) => ({

            name:

                ward.ward_name ||

                ward.Ward_Name ||

                `Ward ${index + 1}`,

            score:

                Number(

                    ward.Composite_Score ??

                    ward.score ??

                    ward.Impact_Mean ??

                    0

                )

        }));

    return (

        <div

            style={{

                background: "var(--card)",

                borderRadius: "24px",

                padding: "25px",

                height: "360px",

                border: "1px solid var(--border)"

            }}

        >

            <h2

                style={{

                    color: "var(--text)",

                    marginBottom: "8px"

                }}

            >

                Top 10 Ward Impact Scores

            </h2>

            <p

                style={{

                    color: "var(--text-muted)",

                    marginBottom: "25px"

                }}

            >

                Generated by CanopyAI Recommendation Engine

            </p>

            <ResponsiveContainer

                width="100%"

                height="80%"

            >

                <LineChart

                    data={chartData}

                >

                    <CartesianGrid

                        stroke="#e5e2d9"

                    />

                    <XAxis

                        dataKey="name"

                        stroke="#717973"

                    />

                    <YAxis

                        stroke="#717973"

                    />

                    <Tooltip />

                    <Line

                        type="monotone"

                        dataKey="score"

                        stroke="#07472e"

                        strokeWidth={3}

                    />

                </LineChart>

            </ResponsiveContainer>

        </div>

    );

}